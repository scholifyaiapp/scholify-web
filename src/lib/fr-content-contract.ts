/*
 * FR's content contract, rewritten for the rebuilt paper.
 *
 * ── What the old contract asserted, and why every figure was wrong ──
 * The previous version read:
 *
 *   sectionA: 350, sectionBQuestions: 350, sectionBCases: 70, sectionC: 50,
 *   flashcards: 150, mixedBanks: 5, mixedBankSize: 30, mockForms: 3
 *
 * Only the last three described the paper. FR's real exam is 15 Section A objective tests at
 * 2 marks, THREE Section B OT cases of five 2-mark tasks, and TWO Section C constructed
 * responses at 20 marks. So:
 *
 *   · 350 Section A items was an inventory target, not an exam fact, and 103 of them were
 *     machine-derived recall drills served alongside authored questions.
 *   · 350 "Section B questions" and 70 cases described a GENERATED Section B. Seventy cases
 *     is over twenty-three sittings' worth of a paper that examines three, and each was a
 *     permutation of one ratio scenario — "In FR case 47, calculate gross profit margin to
 *     two decimals" — composed by completeFrSectionB rather than authored.
 *   · sectionC: 50 counted questions generated by completeFrSectionC, all sharing a single
 *     twenty-point generic rubric that named no standard, no figure and no user. A rubric
 *     that fits fifty different questions marks none of them.
 *   · The study side was the worst of it: FIVE area-chapters for a FIVE-area syllabus. Area B
 *     alone covers seventeen standards from IAS 2 to IFRS 16 and had ONE chapter; Area D
 *     covers single-entity preparation AND full consolidation including an associate, and had
 *     one chapter.
 *
 * ── What this contract polices instead ──────────────────────────
 * The real exam's composition, and the authored content needed to compose three DISJOINT
 * sittings of it. Every figure below is either a fact about the ACCA exam or a floor derived
 * from one, and the test file asserts each against what the loader actually serves.
 */

export const FR_CONTENT_TARGET = {
  /* ── The real exam ──────────────────────────────────────────── */

  /** Section A: 15 objective tests × 2 marks. */
  sectionAQuestions: 15,
  sectionAMarks: 30,
  /** Section B: 3 OT cases × 5 questions × 2 marks. */
  sectionBCases: 3,
  sectionBQuestionsPerCase: 5,
  sectionBMarks: 30,
  /** Section C: 2 constructed responses × 20 marks. */
  sectionCQuestions: 2,
  sectionCMarks: 40,
  /** FR is a three-hour paper. */
  durationMin: 180,
  /** Every objective question in FR is worth 2 marks — Section A and Section B alike. */
  marksPerQuestion: 2,

  mockForms: 3,

  /* ── The authored content that composes it ──────────────────── */

  /**
   * Authored, exam-standard Section A questions. Derived DRILLS do not count, and there are
   * none. The figure is the whole authored bank as the loader serves it: 276 from the
   * per-chapter kits and the depth file, plus 63 of the chapters own inline `check` questions
   * promoted into the bank — which are authored too, one per section, not machine-permuted.
   */
  authoredBank: 339,
  /** The kits alone, excluding the promoted chapter checks. */
  kitQuestions: 276,
  /**
   * The inventory the loader sizes the bank to. Set to the authored total, so
   * completeSectionAFromStudy has nothing left to fill and PaperContent.drills is empty.
   * Deliberately NOT the old 350: a target below the authored bank would be meaningless, and
   * one above it would reintroduce derived filler.
   */
  bankInventoryTarget: 339,
  /** Study chapters in the reading tree, one per syllabus sub-topic group. */
  chapters: 34,
  /**
   * Official syllabus areas the chapters must cover between them: A to E.
   *
   * Chapters 1 to 33 teach the financial reporting content of Areas A to D. Chapter 34 covers
   * Area E, employability and technology skills, which is about operating the CBE rather than
   * about a reporting technique — the same treatment every other paper with an employability
   * area gets. It earns its place: Section C is 40 of the 100 marks and is answered entirely
   * in the spreadsheet and the word processor.
   */
  syllabusAreas: 5,
  /**
   * Authored Section B OT cases. Three mocks × three cases = 9, so this is exactly enough for
   * three DISJOINT sittings at the real unit size.
   */
  otCases: 9,
  /** Marks per OT case: 5 linked questions × 2 marks. */
  otCaseMarks: 10,
  /**
   * Authored Section C questions.
   *
   * SIX would be exactly three disjoint mock sittings of two, and that is the right number
   * for MOCKS. It is far too few for PRACTICE: Section C is 40 of the 100 marks and is where
   * the paper is passed or failed, so a learner who had sat three mocks would have nothing
   * left to work on and the AI Examiner nothing left to mark. Fifteen is the practice bank;
   * the mock composer shuffles it per form and fills each Section C to 40 marks, so the three
   * mocks still compose correctly.
   */
  writtenQuestions: 15,
  /** The floor the mocks alone require: three forms × two questions. */
  minWrittenForMocks: 6,
  writtenMarks: 20,
  flashcards: 150,
  mixedBanks: 5,
  mixedBankSize: 30,

  /* ── Floors that make the paper genuinely examinable ────────── */

  /**
   * Every chapter must carry at least this many authored questions. The bank could satisfy
   * `authoredBank` while leaving whole chapters unexamined, which is exactly the failure mode
   * a per-chapter kit exists to prevent.
   */
  minQuestionsPerChapter: 5,
  /**
   * FR is a computational paper, so a meaningful proportion of the bank must be numeric ENTRY
   * rather than multiple choice. A calculation tested as a four-option MCQ is materially
   * easier than the same calculation as free entry — the candidate can work backwards from
   * the options or eliminate two on magnitude alone.
   *
   * The floor is lower than PM's 80 for a real reason rather than a slack one: roughly half
   * of what FR examines is a TREATMENT DECISION — is this an asset, does it meet the six
   * criteria, is this held for sale, policy or estimate — and those are genuinely tested as
   * multiple choice, in the exam and in the kit. Forcing them into numeric entry would
   * misrepresent the paper.
   */
  minNumericQuestions: 60,
  /**
   * Numeric entry must reach the computational areas rather than clustering in one. Area A is
   * excluded by nature: there is almost nothing to compute in the conceptual framework beyond
   * capital maintenance, and inventing computations for it would misrepresent how it is
   * examined. Area E is excluded for the same reason.
   */
  numericAreas: ["B", "C", "D"] as const,
  /**
   * Section C must examine Areas B, C and D — the three the real paper draws it from — plus
   * Area A, where a question turns on the framework or on an accounting policy dispute. A
   * Section C question on Area E would not be an FR Section C.
   */
  writtenAreas: ["A", "B", "C", "D"] as const,
} as const
